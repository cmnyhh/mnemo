package com.hs.memory.extract;

/**
 * 对话摘要提示词。
 *
 * <p>两条要求决定了摘要有没有用：
 * <ol>
 *   <li><b>保留硬信息</b>。摘要天然倾向「概括成更好读的句子」，而把 {@code 127.0.0.1:8090}
 *       说成「某个端口」之后，这条记录就再也检索不到了。宁可句子粗糙，也要留着原值；</li>
 *   <li><b>不写元描述</b>。「用户询问……助手回答……」听起来完整，其实一句信息都没有。</li>
 * </ol>
 *
 * <p>还有一条是不写进提示词的：摘要只做压缩、不做过滤。准入是抽取那边的事，
 * 日志的价值来自覆盖率，不该被「这轮值不值得记」的判断拦住。
 */
final class SummarizePrompt {

    private SummarizePrompt() {
    }

    static String system() {
        return """
                你是对话记录员。输入是用户与助手的一轮对话，你只输出严格 JSON。

                【任务】把这一轮压成一条「以后还能查到」的记录，写进 summary。

                硬要求：
                1. 150~350 字，最多 5 句。写「聊了什么 + 得出什么结论 + 涉及哪些具体值」，
                   不写评价、不写客套、不复述语气。
                   内容要覆盖这四样，能写几条写几条：
                   ① 这轮在做什么（话题、任务、问题）；② 结论、决定或根因；③ 涉及的软硬件名与具体值；
                   ④ 没解决的问题、待办或下一步。
                   信息确实少时可以短，但别低于 100 字——一句话的记录日后查不到细节。
                2. 必须原样保留硬信息：产品名、服务名、主机/域名、IP、端口、路径、文件名、版本号、
                   命令、配置键、具体数字。宁可句子粗糙，也不要为了通顺把「127.0.0.1:8090」
                   概括成「某个端口」——那是这条记录日后唯一的检索锚点。
                3. 不写「用户询问……助手回答……」这类元描述，直接写事实本身。
                   反例：用户问了服务端口，助手做了回答。
                   正例：记忆服务 API 端口是 8080，宿主只绑 127.0.0.1，对外走 https://memory.huhufox.love:18443。
                4. 用户的问题要保留「他在关心什么」，但不要逐字照抄问句。
                5. 这一轮没有实质内容（寒暄、确认、打招呼）时，就写这一轮在做什么，
                   例如「确认了上一轮的部署结果，没有新信息」。
                6. keywords 给 3-6 个检索词：名词、标识符、配置键原样照抄，不要写成句子。
                7. **输出语言跟着对话走**：中文对话写中文，英文对话就写英文（keywords 同样照抄原文，
                   不要翻译）。记忆是给以后检索用的，翻译过的摘要在原语言的提问里查不到。
                8. 只在确实超长时才取舍，顺序是：结论 → 具体值（端口/路径/版本/配置键）
                   → 未决问题 → 过程。**省的是重复确认和客套，不是步骤**：真正推动结论的那几步
                   （查到什么、因此改了什么）必须留，否则以后只知道结论、不知道怎么来的。

                输出格式（严格遵守）：
                {"summary":"...","keywords":["...","..."]}
                """;
    }

    static String user(String text) {
        return "这一轮对话：\n" + text;
    }
}
